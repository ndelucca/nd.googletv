#!/usr/bin/env bash
# Automated smoke test: is the TV still fully working? Exit code 1 if anything is broken.
#
#   scripts/verify.sh --save-reference   record what "working" looks like (run on a healthy TV)
#   scripts/verify.sh                    system checks (no UI): boot, Wi-Fi, HDMI inputs, remote,
#                                        key services, launcher, protected packages, crashes
#   scripts/verify.sh --ui               also opens every app, an HDMI input, settings and the
#                                        screensaver on screen, and saves screenshots to verify-screens/
#
# What it can't check: the actual picture on an HDMI port, sound, and the physical remote's buttons
# (it checks the remote is connected and injects key events instead).
source "$(dirname "$0")/lib.sh"

REF="$REPO_ROOT/state/verify-reference.txt"
SHOTS="$REPO_ROOT/verify-screens"
MODE="check"; UI=0
for a in "$@"; do
  case "$a" in
    --save-reference) MODE="save" ;;
    --ui) UI=1 ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) die "unknown argument: $a" ;;
  esac
done
ensure_connected
TOTALS_LABEL="verify"

# Services that must be running for the TV to work (HDMI, UI). com.tcl.settings (picture menu) is
# left out: it starts on demand and Android closes it when idle, so "not running" is normal.
REQUIRED_PROCS=(surfaceflinger system_server sitatvservice com.android.systemui com.tcl.tv
                com.tcl.tvinput com.tcl.system.server)

tv_inputs()     { tv_shell dumpsys tv_input | sed -nE 's#^ +(com\.tcl\.tvinput/[^:]+): info:.*#\1#p' | LC_ALL=C sort -u; }
input_devices() { tv_shell dumpsys input | sed -nE 's/^ *Device [0-9]+: (.*)$/\1/p' | grep -v '^virtual' | LC_ALL=C sort -u; }
home_comp()     { tv_shell cmd package resolve-activity --brief -a android.intent.action.MAIN -c android.intent.category.HOME | tail -n1; }
# User-facing apps opened by --ui: third-party apps plus the big preinstalled ones. TCL's own launcher
# entries (input panel, factory, "listen alone"...) are left alone; the launcher is checked separately.
UI_EXTRA_APPS="com.google.android.youtube.tv com.netflix.ninja com.android.vending com.google.android.youtube.tvmusic"
launcher_apps() {
  local third home_pkg
  third="$(tv_shell pm list packages -3 | sed 's/^package://')"
  home_pkg="$(home_comp | cut -d/ -f1)"
  tv_shell cmd package query-activities --brief -a android.intent.action.MAIN -c android.intent.category.LEANBACK_LAUNCHER \
    | grep '/' | sed 's/^ *//' | while read -r comp; do
        pkg="${comp%%/*}"
        [[ "$pkg" == "$home_pkg" ]] && continue
        if grep -qxF "$pkg" <<<"$third" || [[ " $UI_EXTRA_APPS " == *" $pkg "* ]]; then echo "$comp"; fi
      done | LC_ALL=C sort -u
}

if [[ "$MODE" == "save" ]]; then
  mkdir -p "$(dirname "$REF")"
  {
    echo "# Generated by scripts/verify.sh --save-reference on $(date '+%F %T'). What a healthy TV looks like."
    tv_inputs     | sed 's/^/tv_input /'
    input_devices | sed 's/^/input_device /'
    launcher_apps | sed 's/^/launcher_app /'
  } >"$REF"
  log "reference saved to ${REF#"$REPO_ROOT"/}:"
  grep -v '^#' "$REF" | sed 's/^/  /'
  exit 0
fi
[[ -f "$REF" ]] || die "no reference yet: run scripts/verify.sh --save-reference on a healthy TV first"

log "system"
[[ "$(tv_shell getprop sys.boot_completed)" == "1" ]] && report ok "boot" "completed" || report fail "boot" "not completed"
if tv_shell cmd wifi status 2>/dev/null | grep -q "Wifi is connected"; then report ok "wifi" "connected"; else report fail "wifi" "not connected"; fi
if tv_shell dumpsys connectivity | grep -q 'VALIDATED'; then report ok "internet" "validated"; else report fail "internet" "network not validated"; fi

want_home="$(conf_lines "$CONFIG_DIR/home.conf" | awk 'NF {c=$2} END {print c}')"
got_home="$(home_comp)"
[[ "$got_home" == "$want_home" ]] && report ok "home" "$got_home" || report fail "home" "expected $want_home, got $got_home"

log "hardware inputs"
now_inputs="$(tv_inputs)"
while read -r _ id; do
  grep -qxF "$id" <<<"$now_inputs" && report ok "tv input" "${id##*/}" || report fail "tv input" "$id missing (HDMI/tuner)"
done < <(grep '^tv_input ' "$REF")
now_devs="$(input_devices)"
bonded="$(tv_shell dumpsys bluetooth_manager | sed -n '/Bonded devices:/,/^[^ ]/p')"
while read -r _ dev; do
  if grep -qxF "$dev" <<<"$now_devs"; then
    report ok "input device" "$dev"
  elif grep -qF " $dev" <<<"$bonded"; then
    # The Bluetooth remote sleeps after a reboot and only reconnects when a button is pressed.
    report skip "input device" "$dev paired but asleep (connects on the next key press)"
  else
    report fail "input device" "$dev missing (remote/keys)"
  fi
done < <(grep '^input_device ' "$REF")

log "key processes"
for p in "${REQUIRED_PROCS[@]}"; do
  ok=0
  for _ in 1 2 3 4 5 6; do
    tv_shell pidof "$p" >/dev/null 2>&1 && { ok=1; break; }
    sleep 5
  done
  [[ $ok -eq 1 ]] && report ok "process" "$p" || report fail "process" "$p not running"
done
# Chromecast only if it isn't disabled on purpose.
if tv_shell pm list packages -e | grep -qxF "package:com.google.android.apps.mediashell"; then
  if tv_shell dumpsys activity services com.google.android.apps.mediashell | grep -q ServiceRecord; then
    report ok "chromecast" "service running"
  else
    report fail "chromecast" "mediashell enabled but no service running"
  fi
fi

log "packages"
disabled="$(tv_shell pm list packages -d | sed 's/^package://')"
bad=0
while read -r p; do
  [[ -z "$p" ]] && continue
  grep -qxF "$p" <<<"$disabled" && { report fail "protected" "$p is disabled"; bad=1; }
done < <({ printf '%s\n' "${PROTECTED_BUILTIN[@]}"; conf_lines "$CONFIG_DIR/protected.conf"; } | sort -u)
[[ $bad -eq 0 ]] && report ok "protected" "all enabled"

log "crashes since boot"
crashes="$(tv_shell logcat -b crash -d 2>/dev/null | sed -nE 's/^.*Process: ([^,]+), PID.*/\1/p' | sort | uniq -c | sort -rn)"
if [[ -z "$crashes" ]]; then
  report ok "crashes" "none"
else
  while read -r n proc; do
    # A crash loop, or any crash of a component the TV needs, is a failure; a one-off app crash is a warning.
    if (( n >= 3 )) || printf '%s\n' "${REQUIRED_PROCS[@]}" | grep -qxF "$proc"; then
      report fail "crash" "$proc crashed $n times"
    else
      report skip "crash" "$proc crashed $n time(s)"
    fi
  done <<<"$crashes"
fi
anrs="$(tv_shell logcat -b events -d 2>/dev/null | grep -c ' am_anr ' || true)"
(( anrs == 0 )) && report ok "anr" "none" || report skip "anr" "$anrs app-not-responding events"

if [[ $UI -eq 1 ]]; then
  mkdir -p "$SHOTS"; rm -f "$SHOTS"/*.png
  shot() { tv_adb exec-out screencap -p >"$SHOTS/$1.png" 2>/dev/null || true; }
  resumed_pkg() { tv_shell dumpsys activity activities | sed -nE 's/.*mResumedActivity: ActivityRecord\{[^ ]+ [^ ]+ ([^/ ]+)\/.*/\1/p' | head -n1; }
  home_key() { tv_shell input keyevent KEYCODE_HOME; sleep 3; }

  log "UI: launcher"
  tv_shell input keyevent KEYCODE_WAKEUP; home_key
  [[ "$(resumed_pkg)" == "${want_home%%/*}" ]] && report ok "ui home" "launcher on screen" || report fail "ui home" "launcher not in front ($(resumed_pkg))"
  shot 00-home

  log "UI: apps"
  i=1
  while read -r _ comp; do
    pkg="${comp%%/*}"
    tv_shell pm list packages -e | grep -qxF "package:$pkg" || { report skip "ui app" "$pkg disabled"; continue; }
    out="$(tv_shell am start -W -n "$comp" 2>&1)"
    sleep 7
    front="$(resumed_pkg)"
    if grep -q 'Status: ok' <<<"$out" && tv_shell pidof "$pkg" >/dev/null 2>&1 && [[ "$front" == "$pkg" ]]; then
      report ok "ui app" "$pkg"
    elif grep -q 'Status: ok' <<<"$out" && [[ -n "$front" && "$front" != "${want_home%%/*}" ]] \
         && tv_shell pidof "$front" >/dev/null 2>&1; then
      # Some launcher entries hand off to another app (YouTube Music opens inside YouTube).
      report ok "ui app" "$pkg (opens in $front)"
    else
      report fail "ui app" "$pkg did not stay open (front: ${front:-?})"
    fi
    shot "$(printf '%02d' $i)-$pkg"; i=$((i + 1))
    home_key
  done < <(grep '^launcher_app ' "$REF")

  log "UI: HDMI input"
  hdmi="$(grep -m1 'passthroughinput' <<<"$now_inputs" || true)"
  if [[ -n "$hdmi" ]]; then
    tv_shell am start -a android.intent.action.VIEW -d "content://android.media.tv/passthrough/${hdmi//\//%2F}" >/dev/null 2>&1 || true
    sleep 8
    front="$(resumed_pkg)"
    [[ "$front" == "com.tcl.tv" ]] && report ok "ui hdmi" "TV app opened ${hdmi##*/}" || report fail "ui hdmi" "TV app not in front ($front)"
    shot 80-hdmi
    home_key
  fi

  log "UI: settings"
  tv_shell am start -a android.settings.SETTINGS >/dev/null 2>&1; sleep 5
  [[ "$(resumed_pkg)" == "com.android.tv.settings" ]] && report ok "ui settings" "opened" || report fail "ui settings" "did not open ($(resumed_pkg))"
  shot 85-settings
  home_key

  log "UI: screensaver"
  # Close the screensaver app first: in real use it starts from a stopped process, which is
  # exactly what TCL's autostart gate blocks (it doesn't block binding to a running one).
  saver="$(tv_shell settings get secure screensaver_components | cut -d/ -f1)"
  [[ -n "$saver" && "$saver" != "null" ]] && tv_shell am force-stop "$saver"
  sleep 2
  t0="$(tv_shell "date '+%m-%d %H:%M:%S.000'")"
  tv_shell am start -n com.android.systemui/.Somnambulator >/dev/null 2>&1 || true
  sleep 12
  shot 90-screensaver
  if tv_shell "logcat -d -T '$t0'" 2>/dev/null | grep -qE 'Unable to bind dream service|forbid bind service.*DreamActivity'; then
    report fail "ui screensaver" "dream service failed to bind (TCL APP_AUTO_START gate?)"
  elif tv_shell dumpsys dreams | grep -qE 'mCurrentDream(Token)?=[^n]|Dreaming: *true|dreamingComponent'; then
    report ok "ui screensaver" "running"
  else
    report skip "ui screensaver" "could not confirm it started (see screenshot)"
  fi
  tv_shell input keyevent KEYCODE_WAKEUP; home_key
  log "screenshots in ${SHOTS#"$REPO_ROOT"/}/"
fi

echo
print_totals || { warn "verification FAILED"; exit 1; }
log "verification passed"
